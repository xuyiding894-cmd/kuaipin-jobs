export function normalizeLocale(locale) {
  return LOCALES.includes(locale) ? locale : DEFAULT_LOCALE;
}

export function t(locale, key, values = {}) {
  const normalized = normalizeLocale(locale);
  const template = messages[normalized][key] ?? messages[DEFAULT_LOCALE][key] ?? key;
  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}

export function labelFor(locale, group, value) {
  const normalized = normalizeLocale(locale);
  return labels[group]?.[normalized]?.[value] ?? labels[group]?.[DEFAULT_LOCALE]?.[value] ?? value;
}

export function errorText(locale, message) {
  return t(locale, errorKeys[message] ?? message);
}

export function localizeJob(job, locale) {
  const localized = job.localized?.[normalizeLocale(locale)];
  if (!localized) return job;

  return {
    ...job,
    ...localized,
    localized: job.localized
  };
}
